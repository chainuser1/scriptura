"""Prepare the artifacts for hosting (Hugging Face or any static file host). Nothing is uploaded by this script.

Two staging folders are written next to the artifacts (hard-linked, so no extra disk):

  <root>/hosting/search-data/    engine pack + optional word-level index + index.json + README   (no scripture text)
  <root>/hosting/content/        content release (scripture TEXT) + index.json + README          (rights gate D9)

`index.json` is what the app's downloader reads: every pack with its files, byte sizes and SHA-256, so a download can be
verified without trusting the host. The content folder is staged separately because it contains the scripture text,
whose redistribution rights are not cleared (docs/DATA_SOURCES_PLAN.md D9).

  .venv\\Scripts\\python.exe -I tool/prepare_hosting.py [--root ../scriptura/artifacts]
"""
import argparse
import datetime
import hashlib
import json
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / 'generated-artifacts'


def sha256(p):
    h = hashlib.sha256()
    with open(p, 'rb') as f:
        for c in iter(lambda: f.read(1 << 22), b''):
            h.update(c)
    return h.hexdigest()


def place(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists():
        dst.unlink()
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def pack_entry(pid, kind, title, version, folder, files, optional, requires, note):
    return {'id': pid, 'kind': kind, 'title': title, 'version': version, 'folder': folder, 'optional': optional,
            'requires': requires, 'note': note, 'bytes': sum(f['bytes'] for f in files.values()), 'files': files}


def stage_pack(src_dir, out_dir, listed):
    """Hard-link every listed file into out_dir (verifying size) plus manifest.json; returns {rel: {bytes, sha256}}."""
    files = {}
    for rel, meta in listed.items():
        src = src_dir / rel
        if src.stat().st_size != meta['bytes']:
            sys.exit(f'{src} has {src.stat().st_size} bytes, manifest says {meta["bytes"]}')
        place(src, out_dir / rel)
        files[rel] = {'bytes': meta['bytes'], 'sha256': meta['sha256']}
    place(src_dir / 'manifest.json', out_dir / 'manifest.json')
    m = out_dir / 'manifest.json'
    files['manifest.json'] = {'bytes': m.stat().st_size, 'sha256': sha256(m)}  # the app needs it to activate the pack
    return files


SEARCH_README = """---
license: other
tags: [scripture, retrieval, embeddings, onnx, offline]
---

# Scriptura search data

Search indexes and models used by the offline Scriptura reader. **This repository contains no scripture text.**

| Pack | What it is | Size |
|---|---|---|
| `engine-pack-v1` | INT8 BGE-M3 query encoder (ONNX), tokenizer, genome head (FP16), dense / genome / sparse indexes, gated people index | {engine_size} |
| `colbert-pack-v1` | optional word-level (ColBERT) token index, FP16 | {colbert_size} |

Every file is listed with its size and SHA-256 in `index.json`; the app verifies each file before use.

## Provenance and licences

| Component | Origin | Licence |
|---|---|---|
| Query encoder and tokenizer | `BAAI/bge-m3` (INT8 dynamic quantization of the ONNX export) | MIT |
| Genome head, verse genome vectors | trained and generated by this project | see the project's licence notice |
| Dense, sparse and ColBERT indexes | computed from scripture text with BGE-M3; vectors, not text | follow the licence of the underlying text |
| `entities.db` | machine-generated people index (names and verse ids); quality unreviewed | project notice |

Scripture text is distributed separately. Nothing here is legal advice.
"""

CONTENT_README = """# Scriptura content release (scripture text)

> DO NOT PUBLISH until the rights review (DATA_SOURCES_PLAN D9) is complete. A public download is world-readable.

Contents: `content.db` (text for English, Spanish, Tagalog, Cebuano, Greek), `catalog.db` (structure and names),
`phrase-index.db` (exact-phrase search). English text is the King James Version (LDS edition for the non-Bible volumes).
"""

CHECKLIST = """# Publishing checklist (not for upload)

1. search-data
   - Confirm you accept the licence table in README.md (BGE-M3 is MIT; the rest is project-owned or derived).
   - `hf upload <you>/<repo> hosting/search-data . --repo-type model` (or `dataset`). Large files use LFS automatically.
   - Run tool/make_bucket_index.py, then upload hosting/bucket/index.json and scripture-content-v1.zip beside the
     two pack zips. The app's address is `kDefaultDataAddress` in lib/app/hosting.dart.
2. content: only after D9. Options when it is not cleared:
   - keep the repository private and install content from a local folder (works today), or
   - publish a Bible-only English release (public domain KJV text), which needs a reduced build.
3. Never put an access token in the app: anything the app downloads must be public.
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--root', default=str(ROOT.parent / 'scriptura' / 'artifacts'))
    a = ap.parse_args()
    out = Path(a.root) / 'hosting'
    if out.exists():
        shutil.rmtree(out)
    now = datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds')

    # ---- search data ---------------------------------------------------------------------------------------------
    sd = out / 'search-data'
    eng = json.loads((GEN / 'engine-pack' / 'manifest.json').read_text('utf-8'))
    eng_files = stage_pack(GEN / 'engine-pack', sd / 'engine-pack-v1', eng['files'])
    packs = [pack_entry('engine-pack-v1', 'engine', 'Search data', '1', 'engine-pack-v1', eng_files, False, [],
                        'Required for search by meaning, exact phrase and similar verses.')]
    col_dir = GEN / 'colbert-pack-v1'
    if (col_dir / 'manifest.json').exists():
        col = json.loads((col_dir / 'manifest.json').read_text('utf-8'))
        col_files = stage_pack(col_dir, sd / 'colbert-pack-v1', col['shards'])
        packs.append(pack_entry('colbert-pack-v1', 'colbert', 'Word-level index', '1', 'colbert-pack-v1', col_files, True,
                                ['engine-pack-v1'], 'Optional. Slightly more precise results for subtle wording.'))
    size = lambda p: f'{p["bytes"] / 1e9:.2f} GB'  # noqa: E731
    (sd / 'index.json').write_text(json.dumps({'format': 'scriptura-index-v1', 'generated': now, 'packs': packs}, indent=1), 'utf-8')
    (sd / 'README.md').write_text(SEARCH_README.format(engine_size=size(packs[0]), colbert_size=size(packs[1]) if len(packs) > 1 else 'n/a'), 'utf-8')

    # ---- content (text) ----------------------------------------------------------------------------------------
    ct = out / 'content'
    rel = json.loads((GEN / 'release' / 'manifest.json').read_text('utf-8'))
    wanted = {k: v for k, v in rel['files'].items() if k in ('content.db', 'catalog.db', 'phrase-index.db')}
    rel_files = stage_pack(GEN / 'release', ct / rel['release'], {k: {'bytes': v['bytes'], 'sha256': v['sha256']} for k, v in wanted.items()})
    (ct / 'index.json').write_text(json.dumps({
        'format': 'scriptura-index-v1', 'generated': now,
        'packs': [pack_entry(rel['release'], 'release', 'Scripture content', rel['release'], rel['release'], rel_files, False, [],
                             'Scripture text, names and exact-phrase index.')]}, indent=1), 'utf-8')
    (ct / 'README.md').write_text(CONTENT_README, 'utf-8')
    (out / 'PUBLISHING_CHECKLIST.md').write_text(CHECKLIST, 'utf-8')

    print(f'staged at {out}')
    for p in packs:
        print(f'  search-data/{p["folder"]}: {p["bytes"] / 1e9:.2f} GB, {len(p["files"])} files')
    print(f'  content/{rel["release"]}: {sum(f["bytes"] for f in rel_files.values()) / 1e6:.0f} MB (rights gate)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
